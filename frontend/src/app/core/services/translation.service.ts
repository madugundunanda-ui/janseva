  constructor() {
    // React to language changes and persist in LocalStorage
    effect(() => {
      if (typeof window !== 'undefined') {
        window.localStorage.setItem('lang', this.currentLang());
      }
    });
  }

  // Retrieve translation for specific key based on active currentLang signal
  t(key: string): string {
    const lang = this.currentLang();
    const dictionaryForLang = this.dictionary[lang] || this.dictionary['en'];
    return dictionaryForLang[key] || this.dictionary['en'][key] || key;
  }

  setLang(lang: LanguageCode): void {
    this.currentLang.set(lang);
  }
